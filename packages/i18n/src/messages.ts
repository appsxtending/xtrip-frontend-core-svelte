export function uiCopy(
  locale: PresentationLocale = 'en',
): Record<keyof typeof messages.en, string> {
  if (locale === 'en-XA')
    return Object.fromEntries(
      Object.entries(messages.en).map(([key, value]) => [key, `[ ${value} · ${value} ]`]),
    ) as Record<keyof typeof messages.en, string>;
  return messages[locale];
}

